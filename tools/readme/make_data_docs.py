"""Write data/benchmark-stats.json, data/fields.json and docs/schema.md, and check them against the files on disk.

Run from anywhere: python tools/readme/make_data_docs.py
"""
import csv
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import paths  # noqa: E402
import fields  # noqa: E402
import stats  # noqa: E402


def check_headers():
    for name, (_, fl) in fields.CSV.items():
        with open(paths.data(name)) as f:
            header = next(csv.reader(f))
        if header != [k for k, _ in fl]:
            raise SystemExit(f"{name}: columns differ from tools/readme/fields.py: {set(header) ^ {k for k, _ in fl}}")
    on_disk = {f for f in os.listdir(paths.DATA) if f.endswith(".csv")}
    if on_disk != set(fields.CSV):
        raise SystemExit(f"CSV files without a field description: {on_disk ^ set(fields.CSV)}")


def rounded(x, nd=3):
    if isinstance(x, float):
        return round(x, nd)
    if isinstance(x, dict):
        return {k: rounded(v, nd) for k, v in x.items()}
    if isinstance(x, list):
        return [rounded(v, nd) for v in x]
    return x


def table(head, body):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in body]
    return "\n".join(out)


def schema_md():
    L = ["# Schema", "",
         f"Release {stats.RELEASE}. Every file in [`data/`](../data/) and [`examples/sample/`](../examples/sample/), and every field in them. "
         "The flat list is in [`../data/fields.json`](../data/fields.json); JSON Schemas for the JSON files are in [`../data/schema/`](../data/schema/).", "",
         "Shares are percentages of GT-valid pixels in a region. A `region` is `mask` (inside the transparent-object mask) or `nonmask`. "
         "How each number is computed is in [`measurement.md`](measurement.md).", "",
         "An empty cell means the value does not apply to that row. It never means zero.", ""]
    groups = [
        ("Three-bucket results", ["three_bucket_summary.csv", "three_bucket_summary_erode3.csv", "three_bucket_summary_erode5.csv", "three_bucket_summary_biascorrect.csv"]),
        ("Per-image counts", ["three_bucket_per_image.csv", "three_bucket_per_image_erode3.csv", "three_bucket_per_image_erode5.csv", "three_bucket_per_image_biascorrect.csv", "bias_params_biascorrect.csv", "object_proxy.csv"]),
        ("Models and flagging", ["models_summary.csv", "models_transitions.csv", "models_alignment.csv", "flagging_summary.csv"]),
        ("Simulation and calibration", ["synth_vs_real.csv", "calibration_targets.csv", "calibration_search.csv", "calibration_heldout.csv", "fov_check.csv"]),
    ]
    for title, names in groups:
        L += [f"## {title}", ""]
        for n in names:
            desc, fl = fields.CSV[n]
            L += [f"### `data/{n}`", "", desc, "", table(["Field", "Description"], [[f"`{k}`", d] for k, d in fl]), ""]
    L += ["## Other files in `data/`", ""]
    L += [f"### `data/pose_check_output.txt`", "", fields.TEXT["pose_check_output.txt"], ""]
    L += ["### `data/benchmark-stats.json`", "",
          "The headline numbers, generated from the CSVs by `tools/readme/stats.py`. Top-level keys: `release`, `protocol`, `headline`, `groups` (one object per evaluation set, "
          "5% tolerance on the mask), `models` and `calibration_heldout_loss_pp`. Percentages are in percent, errors in cm. Schema: `data/schema/benchmark-stats.schema.json`.", ""]
    for n, (desc, fl) in fields.CONFIGS.items():
        L += [f"### `data/{n}`", "", desc, "", table(["Field", "Description"], [[f"`{k}`", d] for k, d in fl]), ""]
    L += ["### `data/configs/dots.png`", "", "Random dot pattern (1024x1024, 8-bit) used as the projector pattern of the stereo simulator. Generated by `tools/simulation/make_pattern.py`.", ""]
    L += ["### `data/fields.json`", "", "Every file above with its description and field list, as JSON.", ""]
    L += ["## `examples/sample/<sensor>/<seed>/`", "",
          "The open synthetic sample: three scenes for each of `d415` and `d435` (active stereo) and `l515` (ToF approximation), 640x360 pixels. "
          "All depth is uint16 millimetres. Schema for `meta.json`: `data/schema/sample-meta.schema.json`.", "",
          table(["File", "Content"], [[f"`{k}`", d] for k, d in fields.SAMPLE_FILES]), "",
          "### `meta.json`", "", table(["Field", "Type", "Description"], [[f"`{k}`", t, d] for k, t, d in fields.SAMPLE_META]), ""]
    return "\n".join(L)


def main():
    check_headers()
    s = stats.compute()
    with open(paths.data("benchmark-stats.json"), "w") as f:
        json.dump(rounded(s), f, indent=2)
        f.write("\n")
    files = {f"data/{n}": dict(description=d, fields=[dict(name=k, description=v) for k, v in fl]) for n, (d, fl) in fields.CSV.items()}
    files.update({f"data/{n}": dict(description=d, fields=[dict(name=k, description=v) for k, v in fl]) for n, (d, fl) in fields.CONFIGS.items()})
    files["data/pose_check_output.txt"] = dict(description=fields.TEXT["pose_check_output.txt"], fields=[])
    files["examples/sample/<sensor>/<seed>/meta.json"] = dict(description="Scene description of a sample scene.", fields=[dict(name=k, type=t, description=d) for k, t, d in fields.SAMPLE_META])
    with open(paths.data("fields.json"), "w") as f:
        json.dump(dict(release=stats.RELEASE, files=files), f, indent=2)
        f.write("\n")
    with open(os.path.join(paths.ROOT, "docs", "schema.md"), "w") as f:
        f.write(schema_md())
    print("wrote data/benchmark-stats.json, data/fields.json, docs/schema.md")


if __name__ == "__main__":
    main()
